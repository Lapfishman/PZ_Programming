# Дан номер месяца - целое число в диапазоне 1-12
# Определить количество дней в этом месяце для невисокосного года

num = input('Введите номер месяца: ')

while type(num) != int:
    try: num = int(num)
    except:
        print('Ошибка: Некоректно введены данные!')
        num = input('Введите номер месяца: ')

while num < 1 or num > 12:
    print('Ошибка: Число не в диапазоне от 1 до 12!')
    num = input('Введите номер месяца: ')

if num == 2:
    print('В этом месяце: 28 дней')

if num == 1 or num == 3 or num == 5 or num == 7 or num == 9 or num == 11:
    print('В этом месяце: 31 день')

if num == 4 or num == 6 or num == 8 or num == 10 or num == 12:
    print('В этом месяце: 30 дней')
